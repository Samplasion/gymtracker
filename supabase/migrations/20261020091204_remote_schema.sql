end;
$function$;

CREATE OR REPLACE FUNCTION public.export_schema_to_json()
  RETURNS json
  LANGUAGE plpgsql
  AS $function$
DECLARE
    tbl_rec record;
    result_json jsonb := '{}'::jsonb;
    table_rows jsonb;
BEGIN
    -- Iterate through base tables in the 'public' schema not starting with 'boutique_'
    FOR tbl_rec IN 
        SELECT table_name 
        FROM information_schema.tables 
        WHERE table_schema = 'public'
          AND table_type = 'BASE TABLE'
          AND table_name NOT LIKE 'boutique_%'
    LOOP
        -- Dynamically pull all rows from the table as a JSON array
        EXECUTE format(
            'SELECT COALESCE(jsonb_agg(to_jsonb(t)), ''[]''::jsonb) FROM public.%I t', 
            tbl_rec.table_name
        ) INTO table_rows;

        -- Merge table pair {"boutique_table": [...rows]} into the accumulated JSON object
        result_json := result_json || jsonb_build_object(tbl_rec.table_name, table_rows);
    END LOOP;

    RETURN result_json::json;
END;
$function$;

CREATE OR REPLACE FUNCTION public.get_user_stats()
  RETURNS json
  LANGUAGE sql
  AS $function$
    WITH RECURSIVE week_streak AS (
        -- Base Case: Start with the current calendar week (Monday)
        SELECT 
            date_trunc('week', CURRENT_DATE)::timestamp AS week_start, 
            0 AS streak

        UNION ALL

        -- Recursive Step: Step back 1 week for every week that contains at least 1 workout
        SELECT 
            ws.week_start - INTERVAL '1 week', 
            ws.streak + 1
        FROM week_streak ws
        WHERE EXISTS (
            SELECT 1 
            FROM history_workouts hw 
            WHERE hw.starting_date >= ws.week_start 
              AND hw.starting_date < ws.week_start + INTERVAL '1 week'
        )
    )
    SELECT json_build_object(
        'workouts', (SELECT COUNT(*) FROM history_workouts),
        'foods',    (SELECT COUNT(*) FROM foods),
        'weeks',    (SELECT COALESCE(MAX(streak), 0) FROM week_streak)
    );
$function$;

CREATE OR REPLACE FUNCTION public.handle_new_user()
  RETURNS TRIGGER
  LANGUAGE plpgsql
  SECURITY DEFINER
  AS $function$
DECLARE
  new_username TEXT;
  base_username TEXT;
  counter INT := 1;
BEGIN
  -- Determine the starting username (custom or derived from email)
  IF NEW.raw_user_meta_data->>'username' IS NOT NULL THEN
    base_username := NEW.raw_user_meta_data->>'username';
  ELSE
    base_username := split_part(NEW.email, '@', 1);
  END IF;

  new_username := base_username;

  -- Ensure the username is truly unique by appending a counter if necessary
  WHILE EXISTS (SELECT 1 FROM public.profiles WHERE username = new_username) LOOP
    new_username := base_username || '_' || counter;
    counter := counter + 1;
  END LOOP;

  -- Insert the new profile
  INSERT INTO public.profiles (id, email, full_name, username, updated_at)
  VALUES (
    NEW.id, 
    NEW.email, 
    NEW.raw_user_meta_data->>'full_name', 
    new_username,
    NOW()
  );

  RETURN NEW;
END;
$function$;

CREATE OR REPLACE FUNCTION public.rls_auto_enable()
  RETURNS event_trigger
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO 'pg_catalog'
  AS $function$
DECLARE
  cmd record;
BEGIN
  FOR cmd IN
    SELECT *
    FROM pg_event_trigger_ddl_commands()
    WHERE command_tag IN ('CREATE TABLE', 'CREATE TABLE AS', 'SELECT INTO')
      AND object_type IN ('table','partitioned table')
  LOOP
     IF cmd.schema_name IS NOT NULL AND cmd.schema_name IN ('public') AND cmd.schema_name NOT IN ('pg_catalog','information_schema') AND cmd.schema_name NOT LIKE 'pg_toast%' AND cmd.schema_name NOT LIKE 'pg_temp%' THEN
      BEGIN
        EXECUTE format('alter table if exists %s enable row level security', cmd.object_identity);
        RAISE LOG 'rls_auto_enable: enabled RLS on %', cmd.object_identity;
      EXCEPTION
        WHEN OTHERS THEN
          RAISE LOG 'rls_auto_enable: failed to enable RLS on %', cmd.object_identity;
      END;
     ELSE
        RAISE LOG 'rls_auto_enable: skip % (either system schema or not in enforced list: %.)', cmd.object_identity, cmd.schema_name;
     END IF;
  END LOOP;
END;
$function$;

CREATE OR REPLACE FUNCTION public.search_users_weighted (
  search_query text
)
  RETURNS TABLE (
    id        uuid,
    email     text,
    full_name text,
    username  text,
    rank      real
  )
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO ''
  AS $function$
declare
  formatted_query text;
begin
  -- Don't run search if the query is empty or only whitespace
  if trim(search_query) = '' then
    return;
  end if;

  -- Formats each word in the input to support prefix partial matching (e.g. "John Do" -> "John:* & Do:*")
  select string_agg(lexeme || ':*', ' & ')
  into formatted_query
  from unnest(regexp_split_to_array(trim(search_query), '\s+')) as lexeme;

  return query
  select
    profiles.id,
    profiles.email,
    profiles.full_name,
    profiles.username,
    ts_rank(profiles.fts_weighted, to_tsquery('english', formatted_query)) as rank
  from public.profiles
  where profiles.fts_weighted @@ to_tsquery('english', formatted_query)
  order by rank desc;
end;
$function$;

