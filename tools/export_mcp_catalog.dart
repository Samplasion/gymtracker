// Run through tools/export_mcp_catalog.sh: the catalog imports Flutter models.
import 'dart:convert';
import 'dart:io';

import 'package:crypto/crypto.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:gymtracker/data/exercises.dart';
import 'package:gymtracker/i18n/strings.g.dart';
import 'package:gymtracker/model/exercise.dart';

import 'mcp_catalog_migrations.dart';

void main() {
  test('export authoritative MCP catalog', () {
    final translations = {
      for (final locale in AppLocale.values)
        locale.languageCode: locale.buildSync(),
    };
    final exercises = [
      for (final entry in exerciseStandardLibrary.entries)
        for (final exercise in entry.value.exercises)
          {
            'source': 'standard',
            'id': exercise.id,
            'names': {
              for (final entry in translations.entries)
                entry.key: exercise.getDisplayName(entry.value),
            },
            'category': entry.key.name,
            'parameters': exercise.parameters.name,
            'primaryMuscleGroup': exercise.primaryMuscleGroup.name,
            'secondaryMuscleGroups':
                exercise.secondaryMuscleGroups.map((e) => e.name).toList()
                  ..sort(),
            'equipment': exercise.gymEquipment.name,
          },
    ]..sort((a, b) => (a['id'] as String).compareTo(b['id'] as String));
    expect(exercises.map((e) => e['id']).toSet().length, exercises.length);
    for (final exercise in exercises) {
      for (final name in (exercise['names'] as Map).values) {
        expect(name, isA<String>());
        expect(name, isNotEmpty);
        expect(name, isNot(exercise['id']));
      }
    }
    final version = sha256
        .convert(utf8.encode(jsonEncode(exercises)))
        .toString();
    final catalog = {'version': version, 'exercises': exercises};
    final json = '${const JsonEncoder.withIndent('  ').convert(catalog)}\n';
    final file = File('supabase/functions/mcp/catalog.json');
    final sql =
        '''-- Generated by tools/export_mcp_catalog.sh; do not edit.
-- Catalog version: $version
INSERT INTO gymbro_mcp.catalog(singleton, version, exercises)
VALUES (true, '$version', \$catalog\$${jsonEncode(exercises)}\$catalog\$::jsonb)
ON CONFLICT (singleton) DO UPDATE
SET version = EXCLUDED.version, exercises = EXCLUDED.exercises;
''';
    const sqlPath = String.fromEnvironment('CATALOG_MIGRATION');
    if (const bool.fromEnvironment('CHECK_CATALOG')) {
      expect(file.readAsStringSync(), json, reason: 'Regenerate MCP catalog');
      final migration = sqlPath.isEmpty
          ? latestCatalogMigration()
          : File(sqlPath);
      expect(
        migration.readAsStringSync(),
        sql,
        reason: 'Regenerate MCP catalog migration',
      );
    } else {
      final migration = File(
        sqlPath.isEmpty ? catalogMigrationPath(DateTime.now()) : sqlPath,
      );
      writeCatalogMigration(migration, sql);
      file.parent.createSync(recursive: true);
      file.writeAsStringSync(json);
      stdout.writeln('Catalog migration: ${migration.path}');
    }
  });
}
